import { queryJsonSchema } from "../packages/query/src/domain.ts";
import { compile } from "json-schema-to-typescript";
import { reportJsonSchema } from "../packages/core/src/domain.ts";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

const root = resolve(import.meta.dirname, "..");
const document = reportJsonSchema();
const schema = { $schema: "https://json-schema.org/draft/2020-12/schema", ...document.schema };
const types = await compile(schema, "GovernanceReport", {
  bannerComment: "/* Generated by bun run protocol:generate. Do not edit. */",
  additionalProperties: false,
  unknownAny: true,
  style: { singleQuote: false },
});
function format(input: string, path: string): string {
  const formatted = spawnSync(
    resolve(root, "node_modules/.bin/oxfmt"),
    ["--stdin-filepath", path],
    { input, encoding: "utf8" },
  );
  if (formatted.status !== 0) throw new Error(formatted.stderr || "Protocol formatting failed");
  return formatted.stdout;
}
const outputs: Record<string, string> = {
  "packages/protocol/src/generated.ts": format(types, "generated.ts"),
  "packages/protocol/governance-report.schema.json": format(
    `${JSON.stringify(schema, null, 2)}\n`,
    "governance-report.schema.json",
  ),
};
for (const [version, name] of [
  [2, "GovernanceReportV2"],
  ["both", "VersionedGovernanceReport"],
] as const) {
  const extraDocument = reportJsonSchema(version);
  const extraSchema = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    ...extraDocument.schema,
  };
  const suffix = version === 2 ? "v2" : "versioned";
  outputs[`packages/protocol/governance-report-${suffix}.schema.json`] = format(
    JSON.stringify(extraSchema, null, 2) + "\n",
    `governance-report-${suffix}.schema.json`,
  );
  outputs[`packages/protocol/src/generated-${suffix}.ts`] = format(
    await compile(extraSchema, name, {
      bannerComment: "/* Generated by bun run protocol:generate. Do not edit. */",
      additionalProperties: false,
      unknownAny: true,
    }),
    `generated-${suffix}.ts`,
  );
}
const queryDocument = queryJsonSchema();
const querySchema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  ...queryDocument.schema,
};
outputs["packages/protocol/query-result.schema.json"] = format(
  JSON.stringify(querySchema, null, 2) + "\n",
  "query-result.schema.json",
);
outputs["packages/protocol/src/query-generated.ts"] = format(
  await compile(querySchema, "QueryResult", {
    bannerComment: "/* Generated by bun run protocol:generate. Do not edit. */",
    additionalProperties: false,
    unknownAny: true,
  }),
  "query-generated.ts",
);
for (const [path, expected] of Object.entries(outputs)) {
  const file = Bun.file(resolve(root, path));
  if (Bun.argv.includes("--check")) {
    if (!(await file.exists()) || (await file.text()) !== expected)
      throw new Error(`Generated protocol is stale: ${path}; run bun run protocol:generate`);
  } else await Bun.write(file, expected);
}
console.log(
  Bun.argv.includes("--check")
    ? "Protocol generated files are current"
    : "Generated plain JSON Schema and TypeScript protocol",
);
